import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { INITIAL, MIGRATIONS, SCHEMA_VERSION } from '../packages/tribunal/dist/schema.js';

/**
 * The D1 migrations, written from the schema rather than beside it.
 *
 * `wrangler` applies `.sql` files from a migrations directory; `schema.ts` is a
 * list of statements and the tests run against it. Two hand-maintained copies of
 * a schema is the oldest way to deploy a table that the code does not believe
 * in — so one is generated from the other, and `migrations.test.ts` fails if the
 * generated files have drifted from the arrays.
 *
 * One file per step, because `wrangler` records which files it has run: a
 * database deployed two versions ago gets the steps it is missing and nothing
 * else, and a fresh one gets all of them in order. Rewriting an earlier file
 * would reach neither.
 *
 * Run by `yarn build`. Checked by the suite. Never edited by hand.
 */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/tribunal/migrations');

/** The name `wrangler` orders by: a four-digit sequence, then what the step is for. */
export const FILES = [
  '0001_initial.sql',
  // Named for the table it adds, in step order after the initial set.
  '0002_changelog.sql',
  '0003_accessibility.sql',
  '0004_variations.sql',
  '0005_reach.sql',
  '0006_baseline-size.sql',
  '0007_declarations.sql',
  '0008_green-because.sql',
  '0009_moved-bands.sql',
];

/** Generated by tools/tribunal-migrations.mjs from packages/tribunal/src/schema.ts. */
export function migrationText(statements, version) {
  return [
    '-- Generated from packages/tribunal/src/schema.ts by tools/tribunal-migrations.mjs.',
    '-- Do not edit. `migrations.test.ts` fails when this file and the array disagree.',
    `-- Schema version ${version}.`,
    '',
    ...statements.map((statement) => `${statement.trim()};`),
    '',
  ].join('\n');
}

/** Every step, in the order `wrangler` will apply them, with the version each lands on. */
export function migrations() {
  return [
    { file: FILES[0], statements: INITIAL, version: SCHEMA_VERSION - MIGRATIONS.length },
    ...MIGRATIONS.map((statements, index) => ({
      file: FILES[index + 1],
      statements,
      version: SCHEMA_VERSION - MIGRATIONS.length + index + 1,
    })),
  ];
}

const written = migrations();
if (written.some(({ file }) => file === undefined)) {
  // A step with no name is a step that would silently not deploy. Louder than a
  // file called `undefined.sql` landing in the directory `wrangler` reads.
  throw new Error('tribunal-migrations: MIGRATIONS has a step that FILES does not name');
}

mkdirSync(OUT, { recursive: true });

// Stale files are removed rather than left. `wrangler` applies what is in the
// directory, so a renamed step that stayed behind would be applied twice.
for (const name of readdirSync(OUT)) {
  if (name.endsWith('.sql') && !FILES.includes(name)) rmSync(join(OUT, name));
}

for (const { file, statements, version } of written) {
  writeFileSync(join(OUT, file), migrationText(statements, version), 'utf8');
}

process.stdout.write(
  `tribunal-migrations: wrote ${written.length} file(s), ${written.reduce((count, step) => count + step.statements.length, 0)} statement(s)\n`,
);
