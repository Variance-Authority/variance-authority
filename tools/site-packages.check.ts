import { existsSync, readFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseSync } from "oxc-parser";
import { describe, expect, it } from "vitest";

/**
 * A package that is published has a page on the site.
 *
 * The site does not discover packages. `site/app/content/package-docs.ts` holds
 * a hand-written list, each entry pairing a directory name with that
 * directory's README imported as text, and everything downstream reads the
 * list: the reference index, the per-package route, the raw markdown beside it,
 * and the sitemap. Adding a package to the workspace therefore does nothing to
 * the site, and nothing anywhere says so — the new package builds, publishes,
 * is depended on by others, and is simply not there for a reader who arrives
 * from npm. That is how two of them went missing.
 *
 * The rule is total on purpose. A package with a README that is not marked
 * private is a package somebody can install, and there is no editorial reason
 * for an installable package to have no page; if one is genuinely internal it
 * says `"private": true` in its manifest and leaves this list alone. So the
 * exception list this file does not have is the point of it.
 *
 * The list is read out of its source rather than imported, because importing it
 * means resolving `?raw` through the site's bundler, and a check that needs a
 * bundler is a check that stops running. A regular expression over TypeScript
 * is the other way to read a file you are not reading; the parser this
 * repository already depends on is cheaper than the first edge case.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PACKAGES = join(ROOT, "packages");
const CATALOGUE = join(ROOT, "site/app/content/package-docs.ts");

/** The directory names under `packages/` that a reader can install. */
function published(): readonly string[] {
  return readdirSync(PACKAGES, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => {
      const manifest = join(PACKAGES, name, "package.json");
      if (!existsSync(manifest)) return false;
      if (!existsSync(join(PACKAGES, name, "README.md"))) return false;
      const { private: hidden } = JSON.parse(
        readFileSync(manifest, "utf8"),
      ) as {
        readonly private?: boolean;
      };

      return hidden !== true;
    })
    .sort();
}

interface Entry {
  /** The name the site routes and titles the page by. */
  readonly name: string;
  /** The package whose README the entry actually shows, read from the import. */
  readonly shows: string | undefined;
}

interface Node {
  readonly type: string;
  readonly [key: string]: unknown;
}

/**
 * The catalogue's entries, each resolved back to the file it displays.
 *
 * The pairing is the half a reader cannot check: an entry naming one package
 * and importing another renders a page that is wrong rather than missing, and
 * the two names sit far enough apart in the file that a copied import line is
 * an easy way to write one.
 */
function catalogued(): readonly Entry[] {
  const source = readFileSync(CATALOGUE, "utf8");
  const { program } = parseSync(CATALOGUE, source);

  const imported = new Map<string, string>();
  for (const statement of program.body as readonly Node[]) {
    if (statement.type !== "ImportDeclaration") continue;
    const from = /packages\/([^/]+)\/README\.md\?raw$/.exec(
      String((statement.source as { value: unknown }).value),
    );
    if (from === null) continue;
    for (const specifier of (statement.specifiers ?? []) as readonly {
      local: { name: string };
    }[]) {
      imported.set(specifier.local.name, from[1] as string);
    }
  }

  for (const statement of program.body as readonly Node[]) {
    const declaration = (
      statement.type === "ExportNamedDeclaration"
        ? statement.declaration
        : statement
    ) as Node | undefined;
    if (declaration?.type !== "VariableDeclaration") continue;
    for (const declarator of declaration.declarations as readonly {
      id: Node & { name?: string };
      init?: Node & { expression?: Node; elements?: readonly Node[] };
    }[]) {
      if (
        declarator.id.type !== "Identifier" ||
        declarator.id.name !== "packages"
      )
        continue;
      const list =
        declarator.init?.type === "TSAsExpression"
          ? declarator.init.expression
          : declarator.init;
      if (list?.type !== "ArrayExpression") break;

      return (list.elements as readonly { elements: readonly Node[] }[]).map(
        (pair) => {
          const [name, binding] = pair.elements as readonly (Node & {
            value?: unknown;
            name?: string;
          })[];

          return {
            name: String(name?.value),
            shows:
              binding?.name === undefined
                ? undefined
                : imported.get(binding.name),
          };
        },
      );
    }
  }
  throw new Error(`${CATALOGUE} declares no \`packages\` list`);
}

const entries = catalogued();

describe("the site reference", () => {
  it("lists every package somebody can install", () => {
    expect(entries.map((entry) => entry.name).sort()).toEqual(published());
  });

  it("lists each of them once", () => {
    expect(new Set(entries.map((entry) => entry.name)).size).toBe(
      entries.length,
    );
  });

  it("is in the order a reader reads it", () => {
    expect(entries.map((entry) => entry.name)).toEqual(
      [...entries.map((e) => e.name)].sort(),
    );
  });

  describe.each(entries.map((entry) => [entry.name, entry] as const))(
    "%s",
    (name, entry) => {
      it("shows its own README", () => {
        expect(entry.shows).toBe(name);
      });

      it("names the file the page points back at", () => {
        expect(existsSync(join(PACKAGES, name, "README.md"))).toBe(true);
      });
    },
  );
});
