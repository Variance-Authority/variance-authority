import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSync } from 'oxc-parser';
import { describe, expect, it } from 'vitest';

/**
 * A package that is published has a page on the site.
 *
 * The site does not discover packages. `site/app/content/package-docs.ts` holds
 * a hand-written list, each entry pairing a directory name with that directory's
 * README imported as text, and everything downstream reads it: the reference
 * index, the per-package route, the raw markdown beside it, and the sitemap.
 * Adding a package to the workspace therefore does nothing to the site, and
 * nothing anywhere said so — the new package builds, publishes, is depended on
 * by others, and is simply not there for a reader who arrives from npm. That is
 * how two of them went missing, one of them already linked from `docs/`.
 *
 * The rule is total on purpose. A package with a README that is not marked
 * private is a package somebody can install, and there is no editorial reason
 * for an installable package to have no page; a genuinely internal one says
 * `"private": true` in its manifest and leaves the list alone. So the exception
 * list this file does not have is the point of it.
 *
 * Both lists are read out of their source rather than imported, because
 * importing them means resolving `?raw` and JSX through the site's bundler, and
 * a check that needs a bundler is a check that stops running. A regular
 * expression over TypeScript is the other way to read a file you are not
 * reading; the parser this repository already depends on is cheaper than the
 * first edge case.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGES = join(ROOT, 'packages');
const CATALOGUE = join(ROOT, 'site/app/content/package-docs.ts');
const MAP = join(ROOT, 'site/app/components/Packages.tsx');

interface Node {
  readonly type: string;
  readonly [key: string]: unknown;
}

/** The directory names under `packages/` that a reader can install. */
function published(): readonly string[] {
  return readdirSync(PACKAGES, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => {
      const manifest = join(PACKAGES, name, 'package.json');
      if (!existsSync(manifest)) return false;
      if (!existsSync(join(PACKAGES, name, 'README.md'))) return false;
      const { private: hidden } = JSON.parse(readFileSync(manifest, 'utf8')) as {
        readonly private?: boolean;
      };

      return hidden !== true;
    })
    .sort();
}

/** The string value of a named property of an object literal, if it has one. */
function keyed(object: Node, key: string): string | undefined {
  for (const property of (object.properties ?? []) as readonly {
    type: string;
    key: { type: string; name?: string; value?: unknown };
    value: Node & { value?: unknown };
  }[]) {
    if (property.type !== 'Property' || property.value.type !== 'Literal') continue;
    const name =
      property.key.type === 'Identifier' ? property.key.name : String(property.key.value);
    if (name === key) return String(property.value.value);
  }

  return undefined;
}

/** The initializer of a named top-level `const`, with any `as const` unwrapped. */
function declared(path: string, name: string): Node {
  const { program } = parseSync(path, readFileSync(path, 'utf8'));
  for (const statement of program.body as readonly Node[]) {
    const declaration = (
      statement.type === 'ExportNamedDeclaration' ? statement.declaration : statement
    ) as Node | undefined;
    if (declaration?.type !== 'VariableDeclaration') continue;
    for (const declarator of declaration.declarations as readonly {
      id: Node & { name?: string };
      init?: Node & { expression?: Node };
    }[]) {
      if (declarator.id.type !== 'Identifier' || declarator.id.name !== name) continue;
      const value =
        declarator.init?.type === 'TSAsExpression' ? declarator.init.expression : declarator.init;
      if (value !== undefined) return value;
    }
  }
  throw new Error(`${path} declares no \`${name}\``);
}

interface Entry {
  /** The name the site routes and titles the page by. */
  readonly name: string;
  /** The package whose README the entry actually shows, read from the import. */
  readonly shows: string | undefined;
}

/**
 * The catalogue's entries, each resolved back to the file it displays.
 *
 * The pairing is the half a reader cannot check: an entry naming one package and
 * importing another renders a page that is wrong rather than missing, and the
 * two names sit far enough apart in the file that a copied import line is an
 * easy way to write one.
 */
function catalogued(): readonly Entry[] {
  const source = readFileSync(CATALOGUE, 'utf8');
  const { program } = parseSync(CATALOGUE, source);

  const imported = new Map<string, string>();
  for (const statement of program.body as readonly Node[]) {
    if (statement.type !== 'ImportDeclaration') continue;
    const from = /packages\/([^/]+)\/README\.md\?raw$/.exec(
      String((statement.source as { value: unknown }).value),
    );
    if (from === null) continue;
    for (const specifier of (statement.specifiers ?? []) as readonly {
      local: { name: string };
    }[]) {
      imported.set(specifier.local.name, from[1] as string);
    }
  }

  const list = declared(CATALOGUE, 'packages') as Node & { elements?: readonly Node[] };

  return (list.elements ?? []).map((pair) => {
    const [name, binding] = (pair as { elements: readonly Node[] }).elements as readonly (Node & {
      value?: unknown;
      name?: string;
    })[];

    return {
      name: String(name?.value),
      shows: binding?.name === undefined ? undefined : imported.get(binding.name),
    };
  });
}

/**
 * The names the reference index groups under a role.
 *
 * `Packages.tsx` is the second hand-written list and the one a reader actually
 * meets: a package missing from it has a page nothing links to. The component
 * already refuses to render when the two disagree, which is loud but arrives at
 * a site build and does not say which package it is about — so the same question
 * is asked here, by name, where every other one is asked.
 *
 * The entries are collected by shape rather than by position: any object literal
 * inside `PACKAGES` carrying both a `name` and a `role`. Groups are added and
 * reordered as the product's shape changes, and a rule that knew the nesting
 * would fail on the next regrouping rather than on a missing package.
 */
function classified(): readonly string[] {
  const names: string[] = [];
  const collect = (node: unknown): void => {
    if (node === null || typeof node !== 'object') return;
    if (Array.isArray(node)) {
      for (const child of node) collect(child);

      return;
    }
    const record = node as Node;
    if (record.type === 'ObjectExpression') {
      const name = keyed(record, 'name');
      if (name !== undefined && keyed(record, 'role') !== undefined) names.push(name);
    }
    for (const value of Object.values(record)) collect(value);
  };
  collect(declared(MAP, 'PACKAGES'));

  return names;
}

const entries = catalogued();

describe('the site reference', () => {
  it('lists every package somebody can install', () => {
    expect(entries.map((entry) => entry.name).sort()).toEqual(published());
  });

  it('lists each of them once', () => {
    expect(new Set(entries.map((entry) => entry.name)).size).toBe(entries.length);
  });

  it('is in the order a reader reads it', () => {
    expect(entries.map((entry) => entry.name)).toEqual(
      [...entries].map((entry) => entry.name).sort(),
    );
  });

  it('gives every one of them a role on the index', () => {
    const grouped = classified();

    expect([...grouped].sort()).toEqual(published());
    expect(new Set(grouped).size).toBe(grouped.length);
  });

  describe.each(entries.map((entry) => [entry.name, entry] as const))('%s', (name, entry) => {
    it('shows its own README', () => {
      expect(entry.shows).toBe(name);
    });

    it('names the file the page points back at', () => {
      expect(existsSync(join(PACKAGES, name, 'README.md'))).toBe(true);
    });
  });
});
