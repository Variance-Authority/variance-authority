import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCHEMA, SCHEMA_VERSION } from '../packages/tribunal/dist/schema.js';

/**
 * The D1 migration, written from the schema rather than beside it.
 *
 * `wrangler` applies `.sql` files from a migrations directory; `schema.ts` is a
 * list of statements and the tests run against it. Two hand-maintained copies of
 * a schema is the oldest way to deploy a table that the code does not believe
 * in — so one is generated from the other, and `migrations.test.ts` fails if the
 * generated file has drifted from the array.
 *
 * Run by `yarn build`. Checked by the suite. Never edited by hand.
 */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/tribunal/migrations/0001_initial.sql');

/** Generated by tools/tribunal-migrations.mjs from packages/tribunal/src/schema.ts. */
export function migrationText() {
  return [
    '-- Generated from packages/tribunal/src/schema.ts by tools/tribunal-migrations.mjs.',
    '-- Do not edit. `migrations.test.ts` fails when this file and the array disagree.',
    `-- Schema version ${SCHEMA_VERSION}.`,
    '',
    ...SCHEMA.map((statement) => `${statement.trim()};`),
    '',
  ].join('\n');
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, migrationText(), 'utf8');
process.stdout.write(`tribunal-migrations: wrote ${SCHEMA.length} statement(s)\n`);
